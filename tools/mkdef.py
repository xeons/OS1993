#!/usr/bin/env python3
"""Generate a DLL's export table and its import library from a .DEF file.

    LIBRARY UI.DLL
    BASE    0x10100000
    EXPORTS
        wm_create
        wm_close

    mkdef.py ui.def base              -> prints the base address
    mkdef.py ui.def exports out.asm   -> export table, linked into the DLL
    mkdef.py ui.def imports out.asm   -> import library, linked into callers:
                                         one JMP [slot] thunk per function and
                                         a .imports descriptor the loader fills
"""
import re
import sys


def parse(path):
    name, base, exports, in_exports = None, None, [], False
    with open(path) as f:
        for line in f:
            line = line.split(";")[0].strip()
            if not line:
                continue
            words = line.split()
            key = words[0].upper()
            if key == "LIBRARY":
                name = words[1].upper()
            elif key == "BASE":
                base = int(words[1], 0)
            elif key == "EXPORTS":
                in_exports = True
            elif in_exports:
                if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", words[0]):
                    sys.exit(f"{path}: bad export name {words[0]!r}")
                exports.append(words[0])
    if not name or base is None or not exports:
        sys.exit(f"{path}: needs LIBRARY, BASE and EXPORTS")
    return name, base, exports


def exports_asm(name, exports):
    out = [f"; export table of {name} -- generated by tools/mkdef.py", "cpu 386", "bits 32"]
    out += [f"extern {e}" for e in exports]
    out += ["section .exports progbits alloc noexec nowrite align=4",
            "global __exports", "__exports:", f"        dd {len(exports)}"]
    out += [f"        dd __exn_{i}, {e}" for i, e in enumerate(exports)]
    out += ["section .rodata"]
    out += [f'__exn_{i}: db "{e}", 0' for i, e in enumerate(exports)]
    return out


def imports_asm(name, exports):
    tag = re.sub(r"\W", "_", name)
    out = [f"; import library for {name} -- generated by tools/mkdef.py", "cpu 386", "bits 32",
           "section .text"]
    for e in exports:
        out += [f"global {e}", f"{e}:", f"        jmp     [__imp_{e}]"]
    out += ["section .rodata",
            f'__mod_{tag}: db "{name}", 0']
    out += [f'__imn_{e}: db "{e}", 0' for e in exports]
    out += ["align 4", f"__names_{tag}:"]
    out += [f"        dd __imn_{e}" for e in exports]
    out += ["        dd 0",
            "section .data", "align 4", f"__slots_{tag}:"]
    out += [f"__imp_{e}: dd 0" for e in exports]
    out += ["section .imports progbits alloc noexec write align=4",
            f"        dd __mod_{tag}, __names_{tag}, __slots_{tag}"]
    return out


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    name, base, exports = parse(sys.argv[1])
    what = sys.argv[2]
    if what == "base":
        print(f"0x{base:08X}")
        return
    lines = exports_asm(name, exports) if what == "exports" else imports_asm(name, exports)
    with open(sys.argv[3], "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
